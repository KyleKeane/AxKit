<#
.SYNOPSIS
Writes the Menus section of every app's user guide from the command inventory; or checks that each is current
(-Check).

.DESCRIPTION
The maintainer, 2026-11-23: "make the documentation fuly automatically made from the underlyfing data spec for
things like keyboards to aboid documentation drifft" and "this should be done all in code so as much as possible is
automatically generated by scripts". A guide's list of its menus and their keys was written by hand and fell behind
the code; now it is written here from docs\axKit\window-commands.json, the commands every window lists, with their
menus and keys, which the window runs write (tools\AxAutomate --inventory write or rewrite).

A guide takes part when it holds the two marker lines, each on a line of its own:

    <!-- menus: written by tools/guide-menus.ps1 from docs/axKit/window-commands.json; never edit by hand -->
    <!-- end of the menus -->

Everything between them is replaced: one line per menu of the window's own, in the menu bar's order (Session,
Actions, Navigation, Context, the app's others, Options), each command with its key, a submenu's commands in
parentheses after its name; then the keys that have no menu item; then one line for the bundle's menus. The
numbered entries of a recent list ("1. a.md (...)") are left out: they are the user's files, not commands.

-Check writes nothing and exits with 1 when a guide is not what the inventory gives; then run the script without
-Check and commit the guides. test.ps1 and build.yml run the check.
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path | Split-Path -Parent
. (Join-Path $root 'tools\ordinal.ps1')
$startMarker = '<!-- menus: written by tools/guide-menus.ps1 from docs/axKit/window-commands.json; never edit by hand -->'
$endMarker = '<!-- end of the menus -->'
$bundleMenus = @('Window', 'axKit', 'Help')
$firstMenus = @('Session', 'Actions', 'Navigation', 'Context')

$inventory = [IO.File]::ReadAllText((Join-Path $root 'docs\axKit\window-commands.json')) | ConvertFrom-Json

function Format-Command($command) {
    if ($command.keyText) { "$($command.label) ($($command.keyText))" } else { $command.label }
}

function Get-MenuLines($commands) {
    $own = @($commands | Where-Object { -not $_.keyOnly -and $_.menu -and $bundleMenus -notcontains ($_.menu -split ', ')[0] -and $_.label -notmatch '^\d+\. ' })
    $tops = @($own | ForEach-Object { ($_.menu -split ', ')[0] } | Select-Object -Unique)
    $others = @(Sort-Ordinal @($tops | Where-Object { $firstMenus -notcontains $_ -and $_ -ne 'Options' }))
    $order = @($firstMenus | Where-Object { $tops -contains $_ }) + $others + @($tops | Where-Object { $_ -eq 'Options' })
    $lines = New-Object System.Collections.Generic.List[string]
    foreach ($top in $order) {
        $parts = New-Object System.Collections.Generic.List[string]
        foreach ($command in @($own | Where-Object { $_.menu -eq $top })) { $parts.Add((Format-Command $command)) }
        $subs = @($own | Where-Object { $_.menu.StartsWith($top + ', ') } | ForEach-Object { $_.menu.Substring($top.Length + 2) } | Select-Object -Unique)
        foreach ($sub in $subs) {
            $inner = @($own | Where-Object { $_.menu -eq "$top, $sub" } | ForEach-Object { Format-Command $_ })
            $parts.Add("$sub ($($inner -join ', '))")
        }

        $lines.Add("- **$top**: $($parts -join '; ').")
    }

    $keys = @($commands | Where-Object { $_.keyOnly -and $_.keyText } | ForEach-Object { "$($_.keyText) ($($_.label))" })
    if ($keys.Count -gt 0) { $lines.Add("- Keys without a menu item: $($keys -join '; ').") }
    $lines.Add('- **Window**, **axKit** and **Help**: the menus of the bundle, the same in every axKit window; the axKit guide describes them, and F1 lists every key.')
    return $lines
}

$stale = New-Object System.Collections.Generic.List[string]
$unmarked = New-Object System.Collections.Generic.List[string]
$written = 0
foreach ($app in $inventory.apps) {
    $guide = Join-Path $root "docs\$($app.app)\user-guide.md"
    if (-not (Test-Path -LiteralPath $guide)) { continue }
    $text = [IO.File]::ReadAllText($guide)
    $start = $text.IndexOf($startMarker)
    # Every guide of an app the inventory holds has the section (2026-11-24): one listed by hand falls behind the
    # window, as axFile's did.
    if ($start -lt 0) { $unmarked.Add("docs/$($app.app)/user-guide.md"); continue }
    $nl = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
    $end = $text.IndexOf($endMarker, $start)
    if ($end -lt 0) { throw "docs\$($app.app)\user-guide.md has the start marker of the menus and not its end." }
    $body = (Get-MenuLines $app.commands) -join $nl
    $new = $text.Substring(0, $start) + $startMarker + $nl + $body + $nl + $text.Substring($end)
    if ($new -ceq $text) { continue }
    if ($Check) { $stale.Add("docs/$($app.app)/user-guide.md") } else { [IO.File]::WriteAllText($guide, $new, (New-Object System.Text.UTF8Encoding($false))); $written++ }
}

if ($unmarked.Count -gt 0) {
    Write-Host "These guides have no Menus section written from the inventory: $($unmarked -join ', '). Put the two marker lines in their Menus section (as docs/axCalc/user-guide.md has them) and run tools\guide-menus.ps1."
    exit 1
}

if ($Check) {
    if ($stale.Count -gt 0) {
        Write-Host "The Menus section of these guides is not what docs/axKit/window-commands.json gives: $($stale -join ', '). Run tools\guide-menus.ps1 and commit the guides."
        exit 1
    }

    Write-Host 'The guides'' Menus sections are current.'
    exit 0
}

Write-Host "Wrote the Menus section of $written guide(s)."
